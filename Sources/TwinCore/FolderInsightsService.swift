import Foundation

/// Proactive analysis of a folder: orphan (loose, old) files, permission
/// risks, oversized files and empty folders. Pure analysis — no mutation.
public enum FolderInsightsService {

    public struct Insights: Sendable, Equatable {
        /// Files loose in the folder root, untouched for a long time.
        public var orphanFiles: [URL] = []
        /// Files anyone may write to (others-write) or executables in odd places.
        public var permissionRisks: [(url: URL, octal: String)] = []
        public var oversizedFiles: [(url: URL, size: UInt64)] = []
        public var emptyFolders: [URL] = []
        public var looseFileCount: Int = 0

        public static func == (lhs: Insights, rhs: Insights) -> Bool {
            lhs.orphanFiles == rhs.orphanFiles
                && lhs.permissionRisks.map(\.url) == rhs.permissionRisks.map(\.url)
                && lhs.oversizedFiles.map(\.url) == rhs.oversizedFiles.map(\.url)
                && lhs.emptyFolders == rhs.emptyFolders
                && lhs.looseFileCount == rhs.looseFileCount
        }

        public var hasFindings: Bool {
            !orphanFiles.isEmpty || !permissionRisks.isEmpty || !oversizedFiles.isEmpty || !emptyFolders.isEmpty
        }
    }

    public static let orphanAgeDays: Double = 90
    public static let oversizedBytes: UInt64 = 100_000_000

    public static func analyze(
        folder: URL,
        now: Date = Date(),
        fileManager: FileManager = .default
    ) -> Insights {
        var insights = Insights()
        let keys: [URLResourceKey] = [
            .isDirectoryKey, .isRegularFileKey, .fileSizeKey,
            .contentModificationDateKey, .contentAccessDateKey
        ]
        guard let contents = try? fileManager.contentsOfDirectory(
            at: folder, includingPropertiesForKeys: keys, options: [.skipsHiddenFiles]
        ) else { return insights }

        let orphanCutoff = now.addingTimeInterval(-orphanAgeDays * 24 * 3600)

        for url in contents {
            let values = try? url.resourceValues(forKeys: Set(keys))
            if values?.isDirectory == true {
                let children = try? fileManager.contentsOfDirectory(atPath: url.path)
                if children?.isEmpty == true {
                    insights.emptyFolders.append(url)
                }
                continue
            }
            guard values?.isRegularFile == true else { continue }
            insights.looseFileCount += 1

            // Untouched means neither read nor written recently.
            let modified = values?.contentModificationDate ?? .distantPast
            let accessed = values?.contentAccessDate ?? modified
            let lastTouch = min(accessed, modified)
            if lastTouch < orphanCutoff {
                insights.orphanFiles.append(url)
            }

            if let size = values?.fileSize.map(UInt64.init), size > oversizedBytes {
                insights.oversizedFiles.append((url, size))
            }

            if let permissions = try? FilePermissionService.permissions(for: url),
               permissions.others & 0o2 != 0 {
                insights.permissionRisks.append((url, permissions.octalString))
            }
        }

        insights.orphanFiles.sort { $0.lastPathComponent < $1.lastPathComponent }
        insights.oversizedFiles.sort { $0.size > $1.size }
        return insights
    }

    // MARK: - Kartotek (catalog index)

    /// Writes KARTOTEK.md in the folder: every file with size, modified
    /// date and MD5 — a searchable index of what lives where.
    @discardableResult
    public static func generateCatalog(for folder: URL, fileManager: FileManager = .default) throws -> URL {
        let keys: [URLResourceKey] = [.isRegularFileKey, .fileSizeKey, .contentModificationDateKey]
        var files: [URL] = []
        if let enumerator = fileManager.enumerator(at: folder, includingPropertiesForKeys: keys, options: [.skipsHiddenFiles]) {
            for case let url as URL in enumerator {
                if (try? url.resourceValues(forKeys: Set(keys)))?.isRegularFile == true {
                    files.append(url)
                }
            }
        }
        files.sort { $0.path < $1.path }

        let formatter = ISO8601DateFormatter()
        var lines = [
            "# Kartotek — \(folder.lastPathComponent)",
            "",
            "Generated by Twin. \(files.count) file(s).",
            "",
            "| File | Size (bytes) | Modified | MD5 |",
            "|---|---:|---|---|"
        ]
        let canonicalRoot = folder.resolvingSymlinksInPath().path
        for url in files {
            let values = try? url.resourceValues(forKeys: Set(keys))
            let relative = String(url.resolvingSymlinksInPath().path.dropFirst(canonicalRoot.count + 1))
            let modified = values?.contentModificationDate.map { formatter.string(from: $0) } ?? "-"
            let md5 = (try? FileActionService.md5Hex(of: url)) ?? "-"
            lines.append("| \(relative) | \(values?.fileSize ?? 0) | \(modified) | \(md5) |")
        }

        let output = folder.appendingPathComponent("KARTOTEK.md")
        try lines.joined(separator: "\n").write(to: output, atomically: true, encoding: .utf8)
        return output
    }
}
